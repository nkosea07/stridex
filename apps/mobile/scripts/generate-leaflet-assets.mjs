import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const LEAFLET_VERSION = '1.9.4';
const EXPECTED = {
  'leaflet.js': 'sha256-20nQCchB9co0qIjJZRGuk2/Z9VM+kNiyxNV1lvTlZBo=',
  'leaflet.css': 'sha256-p4NxAoJBhIIN+hmNHrzRCf9tD/miZyoHS5obTRR9BMY=',
};

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(mobileRoot, 'package.json'));
const packageJson = require('leaflet/package.json');
if (packageJson.version !== LEAFLET_VERSION) {
  throw new Error(`Expected leaflet ${LEAFLET_VERSION}, found ${packageJson.version}`);
}
const dist = path.join(path.dirname(require.resolve('leaflet/package.json')), 'dist');

function load(name) {
  const source = readFileSync(path.join(dist, name), 'utf8');
  const integrity = `sha256-${createHash('sha256').update(source, 'utf8').digest('base64')}`;
  if (integrity !== EXPECTED[name]) {
    throw new Error(`${name} integrity ${integrity} does not match the published ${EXPECTED[name]}`);
  }
  if (/<\/script/i.test(source)) {
    throw new Error(`${name} contains a closing script tag and cannot be inlined`);
  }
  return source;
}

const js = load('leaflet.js');
const css = load('leaflet.css');
const output = path.join(mobileRoot, 'lib/map/leafletAssets.generated.ts');
writeFileSync(output, [
  '// Generated by scripts/generate-leaflet-assets.mjs from the leaflet npm package. Do not edit.',
  `export const LEAFLET_VERSION = '${LEAFLET_VERSION}';`,
  `export const LEAFLET_JS_INTEGRITY = '${EXPECTED['leaflet.js']}';`,
  `export const LEAFLET_CSS_INTEGRITY = '${EXPECTED['leaflet.css']}';`,
  `export const LEAFLET_JS = ${JSON.stringify(js)};`,
  `export const LEAFLET_CSS = ${JSON.stringify(css)};`,
  '',
].join('\n'));
process.stdout.write(`Wrote ${path.relative(mobileRoot, output)} (leaflet ${LEAFLET_VERSION}, ${js.length + css.length} bytes)\n`);
